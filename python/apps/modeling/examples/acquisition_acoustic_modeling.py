"""
acquisition_acoustic_modeling.py — Multi-shot acoustic forward modeling
driven by a decision file.

Workflow
--------
1. Read a SEP Vp (and optional Rho) file to determine domain extents and
   build a heterogeneous unstructured Cartesian mesh (built once).
2. Read shot/receiver geometry from a decision file (produced by
   create_equispaced_segy.py / decision_create.py).
3. Loop over shots (optionally a subset controlled by --first-shot /
   --last-shot).
4. For each shot: reset wavefield, set source + receivers, run forward
   simulation, save seismogram to a SEG-Y file with geometry headers.

Usage
-----
    python acquisition_acoustic_modeling.py \\
        --vp-file sep_models/vp_layered.H \\
        --decision acquisition/survey \\
        [--rho-file sep_models/rho.H] \\
        [--first-shot 1] [--last-shot 10] \\
        [--f0 10] [--tmax 2.0] [--order 2] \\
        [--output-dir seismoTraces] [--out survey]
"""

