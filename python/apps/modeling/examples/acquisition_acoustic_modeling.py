# ---------------------------------------------------------------------------
# SEG-Y writer (self-contained, IEEE float32 big-endian, format code 5)
# ---------------------------------------------------------------------------

_SEGY_TEXTLINE    = 80
_SEGY_TEXTLINES   = 40
_SEGY_BINARY_SIZE = 400
_SEGY_TRACE_HDR   = 240


def _ebcdic_header(lines):
    rows = []
    for i in range(_SEGY_TEXTLINES):
        raw = lines[i] if i < len(lines) else ""
        rows.append(raw[:_SEGY_TEXTLINE].ljust(_SEGY_TEXTLINE).encode("cp500"))
    return b"".join(rows)


def _binary_reel_header(n_samples, dt_us):
    buf = bytearray(_SEGY_BINARY_SIZE)
    struct.pack_into(">H", buf, 16, min(dt_us,    65535))   # bytes 17-18: dt in µs
    struct.pack_into(">H", buf, 20, min(n_samples, 65535))  # bytes 21-22: n_samples
    struct.pack_into(">H", buf, 24, 5)    # data format: IEEE float32
    struct.pack_into(">H", buf, 28, 256)  # SEG-Y Rev 1.0
    struct.pack_into(">H", buf, 30, 1)    # fixed-length traces
    return bytes(buf)


def _wrd(buf, n, value):
    """Pack big-endian int32 *value* into SEG-Y word *n* (1-based)."""
    struct.pack_into(">i", buf, (n - 1) * 4, int(value))


def _trace_header(seq, field_rec, n_samples, dt_us,
                  sx, sy, sz, rx, ry, rz,
                  w_sx=22, w_sy=23, w_sz=14,
                  w_rx=24, w_ry=25, w_rz=13):
    buf = bytearray(_SEGY_TRACE_HDR)
    _wrd(buf, 1, seq)
    _wrd(buf, 2, seq)
    _wrd(buf, 3, field_rec)
    _wrd(buf, 4, seq)
    _wrd(buf, w_sx, sx);  _wrd(buf, w_sy, sy);  _wrd(buf, w_sz, sz)
    _wrd(buf, w_rx, rx);  _wrd(buf, w_ry, ry);  _wrd(buf, w_rz, rz)
    struct.pack_into(">H", buf, 114, min(n_samples, 65535))
    struct.pack_into(">H", buf, 116, min(dt_us,    65535))
    return bytes(buf)


def write_segy_with_data(path, shot_num, src, rcv_list, data, dt_us,
                         w_sx=22, w_sy=23, w_sz=14,
                         w_rx=24, w_ry=25, w_rz=13):
    """
    Write one SEG-Y file for a single shot with actual seismic trace data.

    Parameters
    ----------
    path     : str          Output file path.
    shot_num : int          Shot index (stored as field record number).
    src      : list [x,y,z] Source coordinates [m].
    rcv_list : list of [x,y,z]  Receiver coordinates [m].
    data     : np.ndarray, shape (n_samples, n_rcv)  Seismogram [float32].
    dt_us    : int          Sample interval [µs].
    """
    n_samples, n_rcv = data.shape
    assert n_rcv == len(rcv_list), \
        f"data columns ({n_rcv}) != receivers ({len(rcv_list)})"

    sx, sy, sz = (int(round(v)) for v in src)
    text_lines = [
        f"C01  SEG-Y shot {shot_num}: {os.path.basename(path)}",
        f"C02  Source  : ({sx}, {sy}, {sz})",
        f"C03  Traces  : {n_rcv}   Samples: {n_samples}   dt: {dt_us} us",
        "C04  Data format: IEEE float-32 big-endian (format code 5)",
        "C05  Generated by acquisition_acoustic_modeling.py",
    ]

    with open(path, "wb") as fh:
        fh.write(_ebcdic_header(text_lines))
        fh.write(_binary_reel_header(n_samples, dt_us))
        for i, rcv in enumerate(rcv_list):
            rx, ry, rz = (int(round(v)) for v in rcv)
            fh.write(_trace_header(
                seq=i + 1, field_rec=shot_num,
                n_samples=n_samples, dt_us=dt_us,
                sx=sx, sy=sy, sz=sz,
                rx=rx, ry=ry, rz=rz,
                w_sx=w_sx, w_sy=w_sy, w_sz=w_sz,
                w_rx=w_rx, w_ry=w_ry, w_rz=w_rz,
            ))
            fh.write(data[:, i].astype(">f4").tobytes())


# ---------------------------------------------------------------------------
# CFL / mesh helper
# ---------------------------------------------------------------------------

def suggest_mesh(lx, ly, lz, vp_max, f0, elem_per_wavelength, order):
    lambda_min = vp_max / (2.0 * f0)
    h_max      = lambda_min / elem_per_wavelength
    ex = max(1, int(np.ceil(lx / h_max)))
    ey = max(1, int(np.ceil(ly / h_max)))
    ez = max(1, int(np.ceil(lz / h_max)))
    hx, hy, hz = lx / ex, ly / ey, lz / ez
    dt = 0.4 * min(hx, hy, hz) / (vp_max * order ** 2)
    return ex, ey, ez, dt


# ---------------------------------------------------------------------------
# Snapshot helper
# ---------------------------------------------------------------------------

def _save_snapshot(solver, mesh, order, t_step, dt, snap_dir, shot_num):
    import matplotlib.pyplot as plt
    nx = mesh.ex * order + 1
    ny = mesh.ey * order + 1
    nz = mesh.ez * order + 1
    pn  = np.array(solver.kk_pn_curr, copy=False).reshape(nz, ny, nx)
    xz  = pn[:, ny // 2, :]
    vmax = float(np.abs(xz).max()) or 1.0
    fig, ax = plt.subplots(figsize=(8, 5))
    im = ax.imshow(
        xz, origin="upper", aspect="auto",
        extent=[mesh.origin_x, mesh.origin_x + mesh.lx, mesh.lz, 0.0],
        cmap="seismic", vmin=-vmax, vmax=vmax,
    )
    ax.set_xlabel("X [m]")
    ax.set_ylabel("Z [m]")
    ax.set_title(f"Shot {shot_num}  t = {t_step * dt:.4f} s  (step {t_step})")
    fig.colorbar(im, ax=ax, shrink=0.8, label="Pressure")
    fig.tight_layout()
    os.makedirs(snap_dir, exist_ok=True)
    fig.savefig(
        os.path.join(snap_dir, f"shot{shot_num:05d}_step{t_step:06d}.png"),
        dpi=100,
    )
    plt.close(fig)


# ---------------------------------------------------------------------------
# Argument parsing
# ---------------------------------------------------------------------------

def parse_args():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    # Velocity / density model
    p.add_argument("--vp-file",  required=True,
                   help="SEP .H header for Vp model [m/s]")
    p.add_argument("--rho-file", default=None,
                   help="SEP .H header for density (optional, default: 1.0)")

    # Decision file and shot range
    p.add_argument("--decision", required=True,
                   help="Rootname of decision file set, without .mapped.data "
                        "(e.g. acquisition/survey)")
    p.add_argument("--first-shot", type=int, default=None,
                   help="First shot index to model, 1-based (default: 1)")
    p.add_argument("--last-shot",  type=int, default=None,
                   help="Last shot index to model, 1-based (default: all)")

    # Coordinate word numbers — must match decision file creation
    p.add_argument("--word-sx", type=int, default=22, help="Source X word (default: 22)")
    p.add_argument("--word-sy", type=int, default=23, help="Source Y word (default: 23)")
    p.add_argument("--word-sz", type=int, default=14, help="Source Z word (default: 14)")
    p.add_argument("--word-rx", type=int, default=24, help="Receiver X word (default: 24)")
    p.add_argument("--word-ry", type=int, default=25, help="Receiver Y word (default: 25)")
    p.add_argument("--word-rz", type=int, default=13, help="Receiver Z word (default: 13)")

    # Mesh / physics
    p.add_argument("--elem-per-wavelength", type=float, default=8.0,
                   help="Elements per minimum wavelength (default: 8)")
    p.add_argument("--f0",    type=float, default=10.0,
                   help="Source peak frequency [Hz] (default: 10)")
    p.add_argument("--tmax",  type=float, default=None,
                   help="Simulation end time [s] (default: 3 * lz / vp_min)")
    p.add_argument("--order", type=int, default=2, choices=[1, 2, 3],
                   help="Polynomial order (default: 2)")
    p.add_argument("--sponge", type=float, default=None,
                   help="Sponge thickness [m] (default: 5%% of min extent)")

    # Output
    p.add_argument("--output-dir", default="seismoTraces",
                   help="Output directory for SEG-Y files (default: seismoTraces)")
    p.add_argument("--out", default=None,
                   help="Rootname for output SEG-Y files "
                        "(default: basename of --decision)")

    # Snapshots
    p.add_argument("--snapshots", action="store_true",
                   help="Save XZ pressure snapshots during simulation")
    p.add_argument("--snapshot-interval", type=int, default=100,
                   help="Steps between snapshots (default: 100)")

    return p.parse_args()


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    args    = parse_args()
    out_root = args.out or os.path.basename(args.decision)

    # -----------------------------------------------------------------------
    # 1. Read Vp SEP model
    # -----------------------------------------------------------------------
    print("=" * 60)
    print(f"Reading Vp model: {args.vp_file}")
    sep_vp = read_sep(args.vp_file)
    lx = sep_vp.n1 * sep_vp.d1
    ly = sep_vp.n2 * sep_vp.d2
    lz = sep_vp.n3 * sep_vp.d3
    vp_min = float(sep_vp.data.min())
    vp_max = float(sep_vp.data.max())
    print(f"  Grid   : nx={sep_vp.n1}  ny={sep_vp.n2}  nz={sep_vp.n3}")
    print(f"  Spacing: dx={sep_vp.d1:.1f}  dy={sep_vp.d2:.1f}  dz={sep_vp.d3:.1f} m")
    print(f"  Domain : lx={lx:.0f}  ly={ly:.0f}  lz={lz:.0f} m")
    print(f"  Vp     : min={vp_min:.0f}  max={vp_max:.0f} m/s")

    # -----------------------------------------------------------------------
    # 2. Mesh and time-step parameters
    # -----------------------------------------------------------------------
    ex, ey, ez, dt = suggest_mesh(
        lx, ly, lz, vp_max, args.f0, args.elem_per_wavelength, args.order
    )
    hx, hy, hz = lx / ex, ly / ey, lz / ez
    tmax   = args.tmax  if args.tmax  is not None else 3.0 * lz / vp_min
    sponge = args.sponge if args.sponge is not None else 0.05 * min(lx, ly, lz)
    n_expected_steps = int(tmax / dt)

    print(f"\nMesh  : {ex} x {ey} x {ez}  "
          f"h = {hx:.1f} x {hy:.1f} x {hz:.1f} m  order = {args.order}")
    print(f"dt    : {dt:.6f} s   tmax : {tmax:.3f} s   "
          f"steps : {n_expected_steps}   sponge : {sponge:.1f} m")

    # -----------------------------------------------------------------------
    # 3. Build mesh (once — shared across all shots)
    # -----------------------------------------------------------------------
    print("\nBuilding mesh ...")
    mesh = StructuredMesh(
        lx=lx, ly=ly, lz=lz,
        ex=ex, ey=ey, ez=ez,
        order=args.order,
        on_nodes=False,
        is_elastic=False,
        free_surface_on_top=True,
        vp_file=args.vp_file,
        rho_file=args.rho_file,
    )
    print(f"  Nodes  : {mesh.numberOfPoints}")
    print(f"  Cells  : {mesh.numberOfCells}")
    print(f"  Backend: {'ModelUnstruct (heterogeneous)' if mesh.heterogeneous else 'ModelStruct'}")

    # -----------------------------------------------------------------------
    # 4. Create solver (once — reset between shots)
    # -----------------------------------------------------------------------
    print("\nCreating solver ...")
    solver = AcousticSolver(
        model=mesh.model,
        order=args.order,
        implem_type=FTSolver.ImplemType.MAKUTU,
        mesh_type=(FTSolver.MeshType.UNSTRUCT
                   if mesh.heterogeneous else FTSolver.MeshType.STRUCT),
        model_location=FTSolver.ModelLocationType.ONELEMENTS,
        sponge_size=[sponge, sponge, sponge],
        surface_sponge=False,
        taper_delta=0.015,
        dt=dt,
        minTime=0.0,
        maxTime=tmax,
        dtSeismo=dt,
        sourceType="ricker2",
        sourceFreq=args.f0,
        lx=mesh.lx, ly=mesh.ly, lz=mesh.lz,
        ex=mesh.ex, ey=mesh.ey, ez=mesh.ez,
        origin_x=mesh.origin_x,
        kk_model_vp=mesh.kk_model_vp,
        kk_model_rho=mesh.kk_model_rho,
    )
    solver.initialize()
    n_steps = solver.n_time_steps
    print(f"  Solver initialized  ({n_steps} time steps)")

    # -----------------------------------------------------------------------
    # 5. Read acquisition geometry from decision file
    # -----------------------------------------------------------------------
    print(f"\nReading decision file: {args.decision}.mapped.data ...")
    d_src, d_rcv, n_shots = read_decision_file(
        args.decision,
        swords=[args.word_sx, args.word_sy, args.word_sz],
        rwords=[args.word_rx, args.word_ry, args.word_rz],
        scalco=1, scalel=1,
    )
    print(f"  Shots in decision file : {n_shots}")

    first = args.first_shot if args.first_shot is not None else 1
    last  = args.last_shot  if args.last_shot  is not None else n_shots

    if first < 1 or last > n_shots or first > last:
        raise SystemExit(
            f"Invalid shot range [{first}, {last}]: decision file has {n_shots} shots."
        )
    n_todo = last - first + 1
    print(f"  Modeling shots : {first} to {last}  ({n_todo} shot{'s' if n_todo > 1 else ''})")

    # -----------------------------------------------------------------------
    # 6. Output directory
    # -----------------------------------------------------------------------
    os.makedirs(args.output_dir, exist_ok=True)
    dt_us = max(1, int(round(dt * 1.0e6)))
    snap_dir = os.path.join(args.output_dir, "snapshots")

    # -----------------------------------------------------------------------
    # 7. Shot loop
    # -----------------------------------------------------------------------
    for shot_idx in range(first, last + 1):
        src_key = f"src{shot_idx}"
        rcv_key = f"rcv_{shot_idx}"

        if src_key not in d_src:
            print(f"\n[WARN] Shot {shot_idx}: '{src_key}' not found — skipping")
            continue
        if rcv_key not in d_rcv:
            print(f"\n[WARN] Shot {shot_idx}: '{rcv_key}' not found — skipping")
            continue

        src_xyz  = d_src[src_key]    # [x, y, z]
        rcv_list = d_rcv[rcv_key]    # [[x,y,z], ...]
        n_rcv    = len(rcv_list)

        print(f"\nShot {shot_idx}/{last}  "
              f"src=({src_xyz[0]:.1f}, {src_xyz[1]:.1f}, {src_xyz[2]:.1f})  "
              f"rcv={n_rcv}")

        solver.resetWaveField()
        solver.updateSourceAndReceiversFromCoords([src_xyz], rcv_list)
        solver.evaluateSource()

        log_every = max(1, n_steps // 10)
        for t in range(n_steps):
            if t % log_every == 0:
                print(f"  step {t:6d}/{n_steps}  t={t * dt:.3f} s",
                      end="\r", flush=True)
            solver.execute(t)
            if args.snapshots and t % args.snapshot_interval == 0:
                _save_snapshot(solver, mesh, args.order,
                               t, dt, snap_dir, shot_idx)
        print()   # newline after \r progress

        seismogram = solver.getPressureAtReceivers()
        # shape: (n_seismo_steps, n_rcv)

        fname = f"{out_root}_shot_{shot_idx:05d}.segy"
        fpath = os.path.join(args.output_dir, fname)
        write_segy_with_data(
            fpath, shot_idx, src_xyz, rcv_list, seismogram, dt_us,
            w_sx=args.word_sx, w_sy=args.word_sy, w_sz=args.word_sz,
            w_rx=args.word_rx, w_ry=args.word_ry, w_rz=args.word_rz,
        )
        print(f"  -> {fpath}  "
              f"({seismogram.shape[0]} samples x {seismogram.shape[1]} traces)")

    print(f"\nDone. {n_todo} shot(s) written to {os.path.abspath(args.output_dir)}/")


if __name__ == "__main__":
    main()
    kokkos.finalize()
