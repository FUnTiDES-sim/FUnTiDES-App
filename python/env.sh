#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# env.sh  —  Setup environment for makutu + FUnTiDES
#
# Usage:
#   source env.sh
#
# FUNTIDES_ENV selects the FUnTiDES environment script (default: the
# funtides_env.sh of the sibling FUnTiDES-install directory).
# ---------------------------------------------------------------------------

# Resolve the directory containing this script (works with `source`)
_ENV_SH_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ---------------------------------------------------------------------------
# 1. FUnTiDES (pyfuntides, kokkos, TPL venv, LD_LIBRARY_PATH): the script is
#    generated by the FUnTiDES install and sources the TPL setup_env.sh.
# ---------------------------------------------------------------------------
_FUNTIDES_ENV="${FUNTIDES_ENV:-${_ENV_SH_DIR}/../FUnTiDES-install/funtides_env.sh}"
if [ ! -f "${_FUNTIDES_ENV}" ]; then
    echo "env.sh: FUnTiDES environment not found: ${_FUNTIDES_ENV}" >&2
    echo "        install FUnTiDES (see README) or set FUNTIDES_ENV" >&2
    unset _ENV_SH_DIR _FUNTIDES_ENV
    return 1 2>/dev/null || exit 1
fi
source "${_FUNTIDES_ENV}" > /dev/null

# ---------------------------------------------------------------------------
# 2. CUDA: pin to a single GPU so Kokkos UVM allocations work correctly.
#    On multi-GPU systems, UVM synchronisation across all devices causes
#    cudaErrorIllegalAddress inside CudaUVMSpace::impl_allocate.
#    Override by setting CUDA_VISIBLE_DEVICES before sourcing this file.
# ---------------------------------------------------------------------------
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0}"

# ---------------------------------------------------------------------------
# 3. makutu (top-level root so `import utilities`, `import workflows` work)
# ---------------------------------------------------------------------------
case ":${PYTHONPATH}:" in
    *":${_ENV_SH_DIR}:"*) ;;
    *) export PYTHONPATH="${_ENV_SH_DIR}${PYTHONPATH:+:${PYTHONPATH}}" ;;
esac

unset _ENV_SH_DIR _FUNTIDES_ENV
